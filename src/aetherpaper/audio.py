"""Optional offline voice generation and scheduled WAV muxing.

The core animation does not depend on an AI model, internet service or TTS.
An external WAV generated by Kokoro/AetherRendering can be supplied per line.
"""
from __future__ import annotations
from pathlib import Path
from tempfile import TemporaryDirectory
import shutil
import subprocess


def speech_events(project):
    offset=0.0
    for scene in project.scenes:
        for action in scene.get('actions',[]):
            if action['type']=='speak':
                yield offset+action['start'],action
        offset+=scene['duration']


def mux_voice(video:Path, project, out:Path, backend:str='none') -> None:
    events=list(speech_events(project))
    if backend not in ('none','espeak'):
        raise ValueError('voice backend must be none or espeak')
    with TemporaryDirectory(prefix='aetherpaper-audio-') as tmp:
        clips=[]
        for idx,(start,action) in enumerate(events):
            if 'audio' in action:
                audio=(project.source.parent/action['audio']).resolve()
                if not audio.is_relative_to(project.source.parent.resolve()):
                    raise ValueError('voice path must stay within scene directory')
                if not audio.is_file():
                    raise FileNotFoundError(f'voice audio missing: {audio}')
                clips.append((start,audio))
            elif backend=='espeak':
                program=shutil.which('espeak-ng') or shutil.which('espeak')
                if not program:
                    raise RuntimeError('espeak/espeak-ng is not installed; use --voice none or provide WAV files')
                wav=Path(tmp)/f'line-{idx}.wav'
                subprocess.run([program,'-s','145','-w',str(wav),action['text']],check=True,stdout=subprocess.DEVNULL)
                clips.append((start,wav))
        if not clips:
            shutil.move(str(video),str(out))
            return
        # Individual fixed delays ensure separate lines stay aligned to scene timing.
        # Mix to stereo 48kHz, trim at the video duration, and preserve the video stream.
        command=['ffmpeg','-y','-hide_banner','-loglevel','error','-i',str(video)]
        nodes=[]
        for idx,(start,path) in enumerate(clips,1):
            command+=['-i',str(path)]
            ms=round(start*1000)
            nodes.append(f'[{idx}:a]aresample=48000,aformat=sample_fmts=fltp:channel_layouts=stereo,adelay={ms}|{ms}[a{idx}]')
        labels=''.join(f'[a{i}]' for i in range(1,len(clips)+1))
        nodes.append(f'{labels}amix=inputs={len(clips)}:duration=longest:dropout_transition=0,atrim=duration={project.duration:.3f}[mix]')
        command+=['-filter_complex',';'.join(nodes),'-map','0:v:0','-map','[mix]',
                  '-c:v','copy','-c:a','aac','-b:a','160k','-t',f'{project.duration:.3f}',
                  '-movflags','+faststart',str(out)]
        proc=subprocess.run(command,stdout=subprocess.PIPE,stderr=subprocess.PIPE,text=True)
        if proc.returncode:
            raise RuntimeError('FFmpeg voice mux failed: '+proc.stderr[-1000:])
